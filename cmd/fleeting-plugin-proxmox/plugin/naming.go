package plugin

import (
	"fmt"
	"strings"

	"github.com/google/uuid"
)

// newInstanceName builds a unique, human-readable VM name for a freshly
// cloned instance: "<base>-<shortUUID>", e.g. "ci-vm-small-creating-a1b2c3d4".
// base is one of Settings.InstanceName{Creating,Running,Removing}, which
// itself is derived from Settings.Name - mirrors the vmware plugin's
// "<prefix>-<uuid>" naming, so instances are distinguishable in the Proxmox
// UI instead of all sharing one literal name per lifecycle state.
func newInstanceName(base string) string {
	return fmt.Sprintf("%s-%s", base, uuid.New().String()[:8])
}

// renameToState builds the name for a different lifecycle state, preserving
// the unique suffix newInstanceName generated at creation, so one instance
// keeps the same identifying suffix across creating/running/removing renames.
func renameToState(currentName, newBase string) string {
	idx := strings.LastIndex(currentName, "-")
	if idx < 0 {
		return newInstanceName(newBase)
	}

	return newBase + currentName[idx:]
}

// hasInstanceNamePrefix reports whether name was generated by
// newInstanceName(base), i.e. is this instance currently in the lifecycle
// state base represents.
func hasInstanceNamePrefix(name, base string) bool {
	return strings.HasPrefix(name, base+"-")
}
